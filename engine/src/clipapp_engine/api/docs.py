"""OpenAPI export and the generated ``docs/api.md``."""

import tempfile
from pathlib import Path
from typing import Any

from clipapp_engine.api.app import create_app

METHODS = ("get", "post", "put", "patch", "delete")
HEADER = """# Engine local API

Generated by `uv run clipapp-engine openapi --markdown -o ../docs/api.md`; do not edit by hand.

Start: `clipapp-engine serve --port 0 --token <token>` listens on `127.0.0.1` and prints one
line `{"ready": true, "port": N}` on stdout. Every route needs the `X-ClipApp-Token` header;
media routes and the `/events` WebSocket also accept `?token=`. Without it: 401. Interactive
docs: `http://127.0.0.1:N/docs` (use *Authorize* to set the token).

Errors are `{"detail": "..."}` with 404 (missing row/file), 409 (wrong state), 422 (invalid
input or media).

## WebSocket `/events`

JSON messages:

- `{"type": "job_progress", "id", "progress"}` (at most 5 per second per job)
- `{"type": "job_status", "id", "status", "error", "output_path"}`
- `{"type": "project_updated", "id"}`

Job states: `queued`, `running`, `done`, `failed`, `cancelled`. Kinds: `prepare`, `full`,
`clip`, `transcribe`. Jobs run one at a time; on restart, unfinished ones become `failed` with
error `interrupted`.
"""


def openapi_schema() -> dict[str, Any]:
    """Return the OpenAPI document of the engine API (built against a throwaway database)."""
    with tempfile.TemporaryDirectory() as tmp:
        app = create_app("", Path(tmp) / "schema.db", start_worker=False)
        schema = app.openapi()
        app.state.db.close()
    return schema


def _ref_name(schema: dict[str, Any]) -> str:
    """Return a short type label for a request/response schema."""
    if "$ref" in schema:
        return str(schema["$ref"]).rsplit("/", 1)[-1]
    if schema.get("type") == "array":
        return f"list[{_ref_name(schema.get('items', {}))}]"
    if "anyOf" in schema:
        return " | ".join(_ref_name(s) for s in schema["anyOf"])
    return str(schema.get("type", "object"))


def api_markdown(schema: dict[str, Any]) -> str:
    """Render the endpoint list of an OpenAPI document as Markdown, grouped by tag."""
    groups: dict[str, list[str]] = {}
    for path, item in schema["paths"].items():
        for method in METHODS:
            op = item.get(method)
            if op is None:
                continue
            body = op.get("requestBody", {}).get("content", {}).get("application/json")
            ok = next((c for c in op["responses"] if c.startswith("2")), "200")
            resp = op["responses"][ok].get("content", {}).get("application/json")
            line = f"- `{method.upper()} {path}`: {op.get('description', op['summary'])}"
            if body:
                line += f" Body: `{_ref_name(body['schema'])}`."
            line += f" → {ok}" + (f" `{_ref_name(resp['schema'])}`" if resp else "")
            groups.setdefault(op.get("tags", ["other"])[0], []).append(line)
    parts = [HEADER]
    for tag, lines in groups.items():
        parts.append(f"## {tag.capitalize()}\n\n" + "\n".join(lines) + "\n")
    parts.append(
        "## Models\n\nSee the `components.schemas` section of `/openapi.json` (TypeScript "
        "types: `app/src/api/schema.ts`, `npm run gen:api`).\n"
    )
    return "\n".join(parts)
